"""Whole sentences a Saudi car dealership's voice agent says, through ``normalize_for_tts``.

Each case is a sentence an agent says or a language model writes for one, and the exact
text the synthesizer is given. The expected text is derived from the rules in
``docs/normalization.md`` and from the forms Saudi agents are attested to say: ونص for
half past, a year from 2020 said ``عشرين ستة وعشرين``, جون for June, كيلو for kilometres,
مية and ميتين for the hundreds, and the teens of the Najdi table of ovos-number-parser
(``ars``). Where the code says something else and the right reading is not in doubt, the
case is a strict xfail that names what is wrong. Where a spelling is a convention rather
than a fact, the case id says which convention it follows.

The formal configuration is the Saudi voice-agent profile of mironik-tts
(``saudi_voice_agent_profile`` in ``src/mironik_tts/text_normalize.py``), composed here from
arbtok's own options. The colloquial one turns on arbtok's colloquial options over it, with
the hundreds named below. mironik's lexicon and its own passes around arbtok, its reading
of a Latin unit symbol among them, are not part of either.

Codes follow arbtok's documented convention: a code of up to seven characters is spelled one
character at a time with English digit names, so ``LX600`` is said "six zero zero". The
scorer reads both that and "ستمية" back to the same digits.
"""
import dataclasses

import pytest

from arbtok.textnorm import ARAB_PHONE_REGIONS, TtsNorm, bundled_tts_lexicon, normalize_for_tts

# mironik-tts IDENTIFIER_WORDS: the words after which a number is read digit by digit.
IDENTIFIER_WORDS = ("كود", "الكود", "رمز", "الرمز", "رقم", "الرقم", "رقمك", "رقمه", "رقمي", "جوال", "جوالك", "جوالي",
                    "هاتف", "موبايل", "تلفون", "فرع", "الفرع", "شاسيه", "الطلب", "الحجز", "code", "number", "no",
                    "phone", "mobile", "branch", "ref", "pin", "otp")
# The hundreds and the thousand as Saudi speech says them: مية and ميتين as the parser's ars table gives
# them, and the spelling, fused or apart, that mironik-tts's colloquial profile lays over the cardinals.
COLLOQUIAL_NUMBER_FORMS = {100: "مية", 200: "ميتين", 300: "ثلاثمية", 400: "اربع مية", 500: "خمس مية",
                           600: "ست مية", 700: "سبع مية", 800: "ثمانمية", 900: "تسع مية", 1000: "الف"}
# The month names Gulf speech uses, January first: the tuple the TtsNorm.month_names docstring gives.
SAUDI_MONTHS = ("يناير", "فبراير", "مارتش", "أبريل", "مي", "جون", "جولاي", "أوقست", "سبتمبر", "أكتوبر", "نوفمبر",
                "ديسمبر")

# numbers-formal-terms-arabic: Standard Arabic oblique cardinals, hundreds spaced, codes spelled.
FORMAL = TtsNorm(strip_controls=False, spell_out_plates=False, spell_out_codes=True, speak_percent=True,
                 keep_code_digits=True, phone_shapes=(), phone_regions=ARAB_PHONE_REGIONS, long_digit_runs=True,
                 phone_prefixes=(), identifier_words=IDENTIFIER_WORDS, cardinal_numbers=True,
                 leave_unspeakable_numbers=True, oblique_numbers=True, space_fused_hundreds=True,
                 dialect_numbers=False, spoken_forms=False, canonical_unicode=False)
# numbers-colloquial-terms-latin: numbers as Saudi speech says them, Latin terms kept, plain orthography.
COLLOQUIAL = dataclasses.replace(FORMAL, spell_out_codes=False, keep_code_digits=False, space_fused_hundreds=False,
                                 colloquial_clock=True, colloquial_years=True,
                                 plain_orthography=True).with_number_forms(COLLOQUIAL_NUMBER_FORMS)
PROFILES = {
    "formal": (FORMAL, "ar"),
    # the formal profile with the bundled car makes and common English terms as its lexicon
    "terms": (FORMAL.with_lexicon({**bundled_tts_lexicon("cars-sa"),
                                   **bundled_tts_lexicon("common-en", pointed=False)}), "ar"),
    "colloquial": (COLLOQUIAL, "ar"),
    "months": (dataclasses.replace(COLLOQUIAL, month_names=SAUDI_MONTHS), "ar"),
    "plates": (dataclasses.replace(COLLOQUIAL, spell_out_plates=True), "ar"),
    # the lect's own cardinals, Najdi for ar-SA, under the colloquial profile
    "najdi": (dataclasses.replace(COLLOQUIAL, dialect_numbers=True), "ar-SA"),
}


def gap(reason):
    return {"gap": reason}


def note(convention):
    return {"note": convention}


def cases(topic, profile, rows):
    out = []
    for n, (written, said, *extra) in enumerate(rows, 1):
        opts = extra[0] if extra else {}
        slug = f"{topic}-{profile}-{n:02d}" + (f"-convention-{opts['note']}" if "note" in opts else "")
        marks = [pytest.mark.xfail(strict=True, reason=opts["gap"])] if "gap" in opts else []
        out.append(pytest.param(profile, written, said, id=slug, marks=marks))
    return out


def check(profile, written, said):
    config, lang = PROFILES[profile]
    assert normalize_for_tts(written, lang, config) == said



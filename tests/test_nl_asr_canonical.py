"""Pairs of transcripts scored under ``CER_CANONICAL``, as a synthetic-speech benchmark scores them.

The first of each pair is what a Saudi car dealership's voice agent was given to say, as an
agent or a language model writes it; the second is what a recognizer wrote back from a
reading of it. Every sentence is written for this file.

A pair that says the same thing must score 0: a number in digits against its words, formal
words against the colloquial ones Saudi speech uses (ونص, مية, ميتين, the teens of the
Najdi table, عشرين ستة وعشرين for 2026, جون for June), and spellings two recognizers write
for one recording. A pair that says something else must score above 0: a wrong number,
hour, minute, month, brand or model digit, ونص against وربع, a dropped word, a repeated
word. The score is the character edit distance between the two canonical forms.

Where the scorer disagrees with what is clearly right, the pair is a strict xfail that
names what is wrong.
"""
import pytest

from arbtok.textnorm import CER_CANONICAL, normalize_asr


def edits(a: str, b: str) -> int:
    row = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        prev, row[0] = row[0], i
        for j, cb in enumerate(b, 1):
            prev, row[j] = row[j], min(row[j] + 1, row[j - 1] + 1, prev + (ca != cb))
    return row[-1]


def score(written: str, heard: str) -> int:
    return edits(normalize_asr(written, CER_CANONICAL), normalize_asr(heard, CER_CANONICAL))


def gap(reason):
    return {"gap": reason}


def pairs(topic, kind, rows):
    out = []
    for n, (written, heard, *extra) in enumerate(rows, 1):
        opts = extra[0] if extra else {}
        marks = [pytest.mark.xfail(strict=True, reason=opts["gap"])] if "gap" in opts else []
        out.append(pytest.param(written, heard, id=f"{topic}-{kind}-{n:02d}", marks=marks))
    return out


